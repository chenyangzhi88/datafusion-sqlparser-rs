fn postgresql_identifier_classes(word: &str) -> u8 {
    POSTGRESQL_KEYWORD_IDENTIFIERS
        .binary_search_by(|(keyword, _)| {
            keyword
                .bytes()
                .cmp(word.bytes().map(|byte| byte.to_ascii_uppercase()))
        })
        .map_or(
            POSTGRESQL_COLUMN_IDENTIFIER | POSTGRESQL_FUNCTION_IDENTIFIER,
            |index| POSTGRESQL_KEYWORD_IDENTIFIERS[index].1,
        )
}

/// Whether an unquoted word can supply PostgreSQL's `ColId` production.
pub(crate) fn is_postgresql_column_identifier(word: &str) -> bool {
    postgresql_identifier_classes(word) & POSTGRESQL_COLUMN_IDENTIFIER != 0
}

/// Whether an unquoted word can supply PostgreSQL's `type_function_name` production.
pub(crate) fn is_postgresql_function_identifier(word: &str) -> bool {
    postgresql_identifier_classes(word) & POSTGRESQL_FUNCTION_IDENTIFIER != 0
}

/// Whether an unquoted word supplies PostgreSQL's `NonReservedWord` production.
pub(crate) fn is_postgresql_non_reserved_word(word: &str) -> bool {
    postgresql_identifier_classes(word) != 0
}
